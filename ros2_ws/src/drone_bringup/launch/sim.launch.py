"""Launch the simulator: Gazebo Jetty, PX4 SITL and the uXRCE-DDS agent.

Usage:
    ros2 launch drone_bringup sim.launch.py
    ros2 launch drone_bringup sim.launch.py headless:=true world:=default.sdf
    ros2 launch drone_bringup sim.launch.py scenario:=/path/to/scenario.yaml

These processes are started:

* the Gazebo server (`gz sim -s`), with PX4's models, worlds, system plugins
  and server config on its search paths, and, unless headless, the Gazebo
  GUI (`gz sim -g`);
* PX4 SITL in standalone mode: it waits for the Gazebo world, spawns the
  vehicle model into it and runs the autopilot against it;
* the Micro XRCE-DDS agent, which exposes PX4's uORB topics to ROS 2 as
  /fmu/in/* and /fmu/out/* (px4_msgs);
* the GNSS injector, which carries the simulated GNSS receiver's output to
  PX4 and drops or degrades it as the scenario says (no scenario: GNSS stays
  healthy). The vehicle model's GNSS reaches PX4 only through this node;
* a ros_gz bridge that brings the simulator's ground-truth pose into ROS 2
  as /sim/ground_truth/odometry, for evaluation only.

PX4, the agent and px4_msgs are installed by the Containerfile; PX4_DIR (set
there) says where. Argument defaults come from config/sim.yaml.
"""

import os
from pathlib import Path

from drone_bringup.sim_config import declare_sim_arguments, load_px4_params
from launch import LaunchDescription
from launch.actions import (
    AppendEnvironmentVariable,
    ExecuteProcess,
    OpaqueFunction,
    SetEnvironmentVariable,
    Shutdown,
)
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node

import drone_sim

PX4_BUILD = "build/px4_sitl_default"
# PX4 instance 0 names the model it spawns <model>_0.
PX4_INSTANCE = 0
# Simulator ground truth in ROS 2 (evaluation only): the vehicle model
# publishes its exact world pose on this Gazebo topic, bridged under the same
# name.
GROUND_TRUTH_TOPIC = "/sim/ground_truth/odometry"
# UDP port PX4's uxrce_dds_client connects to (PX4 default, UXRCE_DDS_PRT).
XRCE_AGENT_PORT = "8888"
# The Gazebo GUI, as a process launch can stop. `gz sim -g` runs the actual
# GUI client as a grandchild and does not pass signals on to it, so it is put
# in a process group of its own (setsid) that the shell terminates as a whole
# when launch signals the shell.
GZ_GUI_CMD = [
    "setsid",
    "sh",
    "-c",
    "trap 'trap \"\" TERM; kill -TERM 0; wait; exit 0' INT TERM; gz sim -g & wait",
]
# PX4 keeps parameters and mission storage in its working directory. They are
# removed before each start so every run begins from the airframe defaults
# (NFR5); flight logs (log/*.ulg) are kept.
PX4_WORK_DIR = Path("/tmp/drone-sitl/px4")
PX4_STATE_FILES = ("parameters.bson", "parameters_backup.bson", "dataman")


def _px4_dir() -> Path:
    px4_dir = Path(os.environ.get("PX4_DIR", "/opt/PX4-Autopilot"))
    if not (px4_dir / PX4_BUILD / "bin" / "px4").is_file():
        raise RuntimeError(
            f"PX4 SITL not found under {px4_dir} (PX4_DIR). The dev container "
            "image is older than the PX4 integration: rebuild it on the host "
            "with `scripts/dev.sh down && scripts/dev.sh up`."
        )
    return px4_dir


def _startup_script(params: dict[str, str]) -> str:
    """PX4 startup script: the stock SITL one, then our parameter overrides.

    The overrides have to come last. PX4's own PX4_PARAM_<NAME> environment
    hook runs before the airframe file, so a value equal to the firmware
    default is dropped and the airframe's `param set-default` then wins.
    """
    lines = [
        "#!/bin/sh",
        "# Generated by drone_bringup sim.launch.py from config/sim.yaml.",
        ". etc/init.d-posix/rcS",
        *(f"param set {name} {value}" for name, value in params.items()),
    ]
    return "\n".join(lines) + "\n"


def _launch_setup(context):
    px4_dir = _px4_dir()
    world = LaunchConfiguration("world").perform(context)
    headless = LaunchConfiguration("headless").perform(context).lower() == "true"
    model = LaunchConfiguration("model").perform(context)
    airframe = LaunchConfiguration("airframe").perform(context)
    scenario = LaunchConfiguration("scenario").perform(context)

    gz_dir = px4_dir / "Tools" / "simulation" / "gz"
    # This project's assets take precedence over PX4's of the same name.
    own_world = drone_sim.worlds_dir() / world
    if own_world.is_file():
        world = str(own_world)
    world_name = Path(world).stem
    models_dir = (
        drone_sim.models_dir()
        if (drone_sim.models_dir() / model / "model.sdf").is_file()
        else gz_dir / "models"
    )
    model_name = f"{model}_{PX4_INSTANCE}"

    PX4_WORK_DIR.mkdir(parents=True, exist_ok=True)
    for name in PX4_STATE_FILES:
        (PX4_WORK_DIR / name).unlink(missing_ok=True)
    startup_script = PX4_WORK_DIR / "rc.drone_sitl"
    startup_script.write_text(_startup_script(load_px4_params()))

    return [
        # --- Gazebo ---------------------------------------------------------
        # Keep Gazebo transport on loopback, for Gazebo and for PX4's bridge
        # alike. With discovery spread over every host interface (the
        # container uses host networking) Gazebo intermittently misses PX4's
        # subscription to a sensor topic and never publishes that sensor, so
        # PX4 comes up without a compass or barometer and refuses to arm.
        SetEnvironmentVariable("GZ_IP", "127.0.0.1"),
        AppendEnvironmentVariable(
            "GZ_SIM_RESOURCE_PATH",
            f"{drone_sim.models_dir()}:{gz_dir / 'models'}:{gz_dir / 'worlds'}",
        ),
        AppendEnvironmentVariable(
            "GZ_SIM_SYSTEM_PLUGIN_PATH",
            str(px4_dir / PX4_BUILD / "src/modules/simulation/gz_plugins"),
        ),
        # World-level systems the vehicle's sensors need (IMU, barometer,
        # magnetometer, NavSat, ...); PX4's worlds do not declare them.
        SetEnvironmentVariable(
            "GZ_SIM_SERVER_CONFIG_PATH",
            str(px4_dir / "src/modules/simulation/gz_bridge/server.config"),
        ),
        # Server and GUI are started here, as two processes, rather than
        # through ros_gz_sim's gz_sim.launch.py. That one runs a combined
        # `gz sim` under a shell: launch's shutdown signals reach the shell
        # instead of Gazebo, and the server waits for a GUI nobody signals, so
        # Gazebo outlives the launch whenever the launch ends by itself (e.g.
        # after a mission) rather than by a terminal Ctrl-C. `gz` execs the
        # server, so here the launched process is the server itself.
        ExecuteProcess(
            name="gazebo",
            cmd=["gz", "sim", "-s", "-r", world],
            output="screen",
        ),
        *(
            []
            if headless
            else [ExecuteProcess(name="gazebo_gui", cmd=GZ_GUI_CMD, output="screen")]
        ),
        # --- PX4 SITL -------------------------------------------------------
        ExecuteProcess(
            name="px4",
            cmd=[
                str(px4_dir / PX4_BUILD / "bin" / "px4"),
                "-d",  # no interactive shell
                "-s",
                str(startup_script),
                str(px4_dir / PX4_BUILD / "etc"),
                "-w",
                str(PX4_WORK_DIR),
            ],
            additional_env={
                # Gazebo is started above; PX4 only attaches and spawns.
                "PX4_GZ_STANDALONE": "1",
                "PX4_GZ_WORLD": world_name,
                # PX4 spawns <PX4_GZ_MODELS>/<model>/model.sdf; the airframe
                # is given by number because our model's name matches none.
                "PX4_GZ_MODELS": str(models_dir),
                "PX4_SIM_MODEL": f"gz_{model}",
                "PX4_SYS_AUTOSTART": airframe,
            },
            output="screen",
            # Without the autopilot the rest of the stack is useless.
            on_exit=Shutdown(reason="PX4 SITL exited"),
        ),
        # --- uXRCE-DDS agent (PX4 <-> ROS 2) --------------------------------
        ExecuteProcess(
            name="xrce_agent",
            cmd=["MicroXRCEAgent", "udp4", "-p", XRCE_AGENT_PORT],
            output="log",
        ),
        # --- GNSS receiver -> PX4, with scenario-driven loss ----------------
        Node(
            package="gnss_injector",
            executable="gnss_injector",
            parameters=[
                {"scenario": scenario, "world": world_name, "model": model_name}
            ],
            output="screen",
        ),
        # --- Ground truth -> ROS 2 (evaluation only) ------------------------
        Node(
            package="ros_gz_bridge",
            executable="parameter_bridge",
            name="ground_truth_bridge",
            arguments=[f"{GROUND_TRUTH_TOPIC}@nav_msgs/msg/Odometry[gz.msgs.Odometry"],
            output="log",
        ),
    ]


def generate_launch_description() -> LaunchDescription:
    return LaunchDescription(
        [*declare_sim_arguments(), OpaqueFunction(function=_launch_setup)]
    )
